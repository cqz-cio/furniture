const mergeLocaleMessages = (target, source) => {
  Object.entries(source).forEach(([key, value]) => {
    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      target[key] &&
      typeof target[key] === "object" &&
      !Array.isArray(target[key])
    ) {
      mergeLocaleMessages(target[key], value);
      return;
    }

    target[key] = value;
  });
};

